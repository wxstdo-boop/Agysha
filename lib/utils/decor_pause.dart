import 'package:material_ui/material_ui.dart';

/// Признак «поверх экрана лежит модальный слой»: нижний лист, диалог, меню,
/// всплывающее окно выбора.
///
/// Зачем отдельный флаг. Flutter сам гасит тикеры у роутов, которые целиком
/// накрыты НЕПРОЗРАЧНЫМ роутом, — но `PopupRoute` (а это и
/// `ModalBottomSheetRoute`, и диалоги) непрозрачным не считается: под листом
/// видно затемнённый экран. Поэтому вечные декоративные циклы продолжали
/// тикать под открытой модалкой и перерисовывали полноэкранные слои, которых
/// никто не видит. На слабом GPU это ровно те кадры, что попадают в отчёт
/// «тормозит: ModalBottomSheetRoute».
///
/// Пауза безопасна для картинки: контроллеры не сбрасываются, а значения
/// берутся из абсолютного `elapsed` (см. `AmbientVsync`), поэтому после
/// закрытия модалки движение продолжается без рывка.
final ValueNotifier<bool> decorCoveredByModal = ValueNotifier<bool>(false);
