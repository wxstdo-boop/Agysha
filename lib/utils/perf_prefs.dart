import 'package:flutter/widgets.dart';

/// Режим «Оптимизация»: анимации остаются как есть, но приложение тратит
/// меньше кадрового бюджета.
///
/// Что именно дешевеет (ничего не исчезает и не «щёлкает»):
///  * декоративные вечные петли тикают реже — их частота считается от
///    частоты экрана, а под нагрузкой декор сам уступает дорогу
///    ([JankProbe.ambientBackoff]);
///  * карточки не наклоняются в 3D под пальцем: перспективный Transform
///    поднимает слой и перерисовывает его каждый кадр драга.
///
/// Кеш картинок режим НЕ трогает. Раньше он ужимался до 64 МБ / 400 картинок,
/// и это оказалось ровно тем, из-за чего «после включения всё подлагивает»:
/// включение выбивало из кеша уже декодированные обложки и аватары, и при
/// прокрутке они декодировались заново — в кадре.
///
/// Переходы, шторки, `AnimatedSize`/`AnimatedSwitcher` и прочие анимации
/// состояния НЕ трогаются: именно это просил владелец — «пусть не убирает
/// анимации, а делает что-то другое, чтобы не лагало».
abstract final class PerfPrefs {
  PerfPrefs._();

  /// Живой флаг тумблера «Оптимизация» в настройках.
  static final ValueNotifier<bool> enabled = ValueNotifier<bool>(false);

  static bool get active => enabled.value;

  /// Раз во сколько кадров тикать декоративным циклам.
  ///
  /// Считается от ЧАСТОТЫ ЭКРАНА, а не от константы: цель — те же ~20 fps
  /// дыхания, что и на 60 Гц. С константой 3 на 120-герцовом телефоне петли
  /// шли 40 раз в секунду, и каждый тик — полноэкранная перерисовка слоя:
  /// телефон с 120 Гц получал вдвое больше работы, чем такой же с 60 Гц.
  /// Отсюда же и «иногда норм, иногда лагает»: экран сам переключает частоту
  /// (60 в покое, 120 при касании), и нагрузка от декора прыгала вдвое.
  static int get ambientEveryFrames {
    final hz = refreshRate;
    if (hz >= 90) return 6;
    if (hz >= 72) return 4;
    return 3;
  }

  /// Частота экрана в герцах. 60 — если система не сказала.
  static double get refreshRate {
    try {
      final displays = WidgetsBinding.instance.platformDispatcher.displays;
      if (displays.isEmpty) return 60;
      final hz = displays.first.refreshRate;
      return hz > 1 ? hz : 60;
    } catch (_) {
      return 60;
    }
  }

  static bool _installed = false;

  /// Точка установки режима из `main` до `runApp`. Лимиты кеша картинок
  /// намеренно не выставляются: см. комментарий к классу.
  static void install() {
    if (_installed) return;
    _installed = true;
  }
}
