#!/usr/bin/env bash
# Фильтр заметок релиза.
#
# На вход — строки вида «- <заголовок коммита>» (их печатает
# `git log --no-merges --pretty=format:'- %s'`). На выход — только те, что
# интересны пользователю.
#
# Зачем: заметки релиза и fastlane-changelog собираются из заголовков коммитов,
# и служебные коммиты («F-Droid: рецепт на тег…», «docs(AGENTS): …», «ship: …»)
# утекали в «Что нового» на GitHub и в F-Droid. Пользователь видел внутреннюю
# кухню вместо изменений приложения.
#
# Правило простое: отбрасываем строки с префиксом Conventional Commits из
# служебного набора (docs/chore/ci/style/test/build/refactor) и наши
# локальные префиксы (F-Droid/fdroid/ship/release/Документация/Переименование).
# Всё остальное — пользовательское («Полировка…», «Питание: …», «feat…»).
#
# Два режима:
#   без флагов  — плоский список для fastlane-changelog (F-Droid режет его по
#                 500 символам, поэтому ни заголовков, ни подписей);
#   --sections  — тело GitHub-релиза: короткий человеческий ввод, пункты по
#                 блокам «Новое / Плавнее / Починили» и подпись. Заголовки без
#                 `#`, чтобы текст не выглядел мусором, если его отдадут
#                 fastlane.
#
# Скрипт намеренно всегда завершается успешно: пустой поток — не ошибка, а
# повод для вызывающей стороны подставить запасной текст.
set -uo pipefail

# Служебные префиксы, плюс отдельно вычищаем зависимости: строки dependabot
# и «Bump x from a to b» — это не изменения приложения, и в заметках они
# выглядели как мусор из чужого бота.
grep -vE '^- (F-Droid|fdroid|ship|release|Документация|Переименование|docs|chore|ci|style|test|build|refactor|deps)(\([^)]*\))?(:|$)' \
  | grep -viE 'dependabot|^- bump[ (:]|^- bump$' \
  | python3 -c '
import re, sys

SECTIONS = "--sections" in sys.argv[1:]

# Темы для эмодзи. Порядок важен: первое совпадение выигрывает, поэтому
# узкие темы идут выше общих.
EMOJI_RULES = [
    (("наклон", "тилт", "3d", "пин", "pin"), "🫧"),
    (("клавиат", "ввод", "букв"), "⌨️"),
    (("поиск", "источник"), "🔎"),
    (("ада", "ии", "провайдер", "ответ"), "🍑"),
    (("будильник", "тест"), "⏰"),
    (("питани", "лимит", "тренд", "приём", "прием"), "🍽️"),
    (("зачёрк", "зачерк", "зачёркиван"), "✍️"),
    (("скролл", "прокрут"), "🌊"),
    (("плавн", "анимац", "отдач"), "🫧"),
    (("баг", "фикс", "исправ", "чиним"), "🛠️"),
]

# Что считаем исправлением, а что — шлифовкой. Остальное попадает в «Новое».
FIX_WORDS = ("баг", "фикс", "исправ", "чиним", "почин", "не работа", "пада",
             "не ставил", "не открыв", "не запус", "не появл", "не груз",
             "лома", "пропада", "зависа", "дёрга", "дерга", "тормоз", "лаг")
POLISH_WORDS = ("плавн", "анимац", "отдач", "полиров", "быстрее", "ускор",
                "мягч", "наклон", "тилт", "3d", "перелив", "свечен", "красив",
                "аккурат", "чище", "контраст", "читаем", "тише", "громче")

# Внутренний жаргон, который в заметках читается как тикет из трекера.
JARGON = [
    (r"\bфикс\b", "исправление"),
    (r"\bрегресс\b", "откат"),
    (r"\bрефактор\w*\b", "внутренняя уборка"),
    (r"\bмерж\w*\b", "слияние"),
    (r"\bкоммит\w*\b", "изменения"),
]

# Сокращения из быстрых коммитов: в релизе они читаются как переписка в
# чате, а не как заметка для человека.
SHORTENINGS = [
    (r"\bи т\s?п\b\.?", "и так далее"),
    (r"\bитп\b\.?", "и так далее"),
    (r"\bи т\s?д\b\.?", "и так далее"),
    (r"\bт\s?п\b\.?", "так далее"),
    (r"\bи пр\b\.?", "и прочее"),
    (r"\bт\.е\b\.?", "то есть"),
]

# Код в заметке читается как чужая кухня: «alarms_screen», «SettingsService»,
# «lib/services/update_service.dart». Пользователю такие слова ничего не
# говорят, поэтому имена файлов, классов и ключей вырезаем, а фразу чиним —
# если после чистки от неё ничего не осталось, пункт не печатаем вовсе.
CODEISH = [
    (r"`[^`]*`", " "),
    (r"\b[vV]?\d+\.\d+(?:\.\d+)?(?:\+\d+)?\b", " "),
    (r"(?<![\w.+])\.(?!\d)", " "),
    (r"\b[\w-]*\.[A-Za-z]{2,6}\b", " "),
    (r"\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b", " "),
    (r"\b[A-Z][A-Za-z0-9]*(?:Service|Screen|Widget|Sheet|Store|Controller|Provider|"
     r"Notifier|Painter|Card|Test|Model|Helper|Utils)\b", " "),
    (r"\b[a-z]+[A-Z][A-Za-z0-9]*\b", " "),
    (r"(?:^|\s)(?:[\w.-]+/){2,}[\w.-]+", " "),
    (r"\b[a-z0-9]+(?:\.[a-z0-9]+){2,}\b", " "),
]

# Слова, на которых фраза после чистки обрывается: «В  добавлена …» или
# «… теперь работает в». Хвост из них снимаем.
DANGLING = ("в", "во", "на", "из", "с", "со", "к", "ко", "по", "для", "от",
            "до", "за", "под", "над", "при", "и", "а", "но", "или", "что",
            "как", "это", "—", "-", "–")


def scrub_code(text):
    for pat, rep in CODEISH:
        text = re.sub(pat, rep, text)
    text = re.sub(r"\s*\(\s*\)", " ", text)
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    text = re.sub(r"([,;:])(?=[^\s\d])", r"\1 ", text)
    text = re.sub(r"\s{2,}", " ", text).strip(" .,;:—-")
    # «Полировка: …», «Тест: …» — шапка коммита; снимаем её до чистки
    # хвостов, иначе связка «и» остаётся в начале пункта.
    text = re.sub(r"^(полировка|плавность|правки|прочее|тест|фикс)\s*[:—-]\s*",
                  "", text, flags=re.I)
    for _ in range(4):
        head, _, tail = text.rpartition(" ")
        if tail.lower() in DANGLING:
            text = head.strip(" .,;:—-")
        else:
            break
    # Обрубок после чистки («И больше не дёргают фон») начинается со связки —
    # снимаем её с начала так же, как с конца.
    for _ in range(4):
        head, _, rest = text.partition(" ")
        if head.lower() in DANGLING:
            text = rest.strip(" .,;:—-")
        else:
            break
    return text


def humanize(text):
    text = scrub_code(text)
    for pat, rep in JARGON + SHORTENINGS:
        text = re.sub(pat, rep, text, flags=re.I)
    # «Тема: деталь» из заголовка коммита читается как предложение только с
    # тире — двоеточие оставляло ощущение списка из changelog.
    # «Полировка — …», «Плавность — …»: в коммитах это шапка раздела, в
    # заметке — просто лишнее слово перед сутью.
    text = re.sub(r"^(полировка|плавность|правки|прочее)\s*[:—-]\s*", "",
                  text, flags=re.I)
    m = re.match(r"^([^:]{3,60}):\s+(.+)$", text)
    if m:
        head, tail = m.group(1), m.group(2)
        if not head.lower().startswith(("http", "https")):
            text = head + " — " + tail
    # Пунктуация: запятая не липнет к слову, но и не отрывается от него
    # лишним пробелом. Раньше «Скролл , поле ввода» и «плавнo.Сразу»
    # приезжали прямо в релиз — это читалось как неграмотная спешка.
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    text = re.sub(r"([,;:])(?=[^\s\d])", r"\1 ", text)
    text = re.sub(r"(?<!\d)\.(?=[А-Яа-яA-Za-z])", ". ", text)
    text = re.sub(r"\s{2,}", " ", text)
    text = text.strip(" .")
    if text:
        text = text[0].upper() + text[1:]
    return text

def section_of(low):
    if any(k in low for k in FIX_WORDS):
        return "fix"
    if any(k in low for k in POLISH_WORDS):
        return "polish"
    return "new"

buckets = {"new": [], "polish": [], "fix": []}
order = []
seen = set()

# Пункт, к которому цепляются подробности из тела коммита. Без него заметка
# релиза из одного коммита оставалась ОДНОЙ строкой на весь выпуск:
# заголовок в полфразы, а всё человеческое («что было не так») лежало в теле
# и до читателя не доезжало.
last_item = None

# Сколько знаков подробностей оставляем. Две-три фразы — это уже абзац,
# который читают; простыня из тела коммита превращает заметку в отчёт.
DETAIL_LIMIT = 300


def clip_detail(text):
    text = re.sub(r"\s{2,}", " ", text).strip()
    # Склеенное тело коммита приходит с висящим двоеточием или тире —
    # в заметке это читается как обрубок.
    text = text.strip(" -–—:;,")
    if not text:
        return ""
    if len(text) > DETAIL_LIMIT:
        cut = text[:DETAIL_LIMIT]
        dot = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
        if dot > DETAIL_LIMIT * 0.55:
            text = cut[: dot + 1]
        else:
            text = cut.rsplit(" ", 1)[0].rstrip(",;:—-") + "…"
    text = text[0].upper() + text[1:]
    if not text.endswith((".", "!", "?", "…")):
        text += "."
    return text

def parts_of(text):
    """Один заголовок коммита часто перечисляет несколько правок через «;».

    В релизе это читалось как пункт-простыня, а после обрезки — половина
    работы пропадала. Такие перечисления делим на отдельные пункты.
    Одиночную «;» внутри обычной фразы не трогаем: делим только когда
    частей две и больше и каждая из них — самостоятельная фраза.
    """
    if ";" not in text:
        return [text]
    pieces = [p.strip() for p in text.split(";")]
    substantial = [p for p in pieces if len(p) >= 12]
    if len(substantial) < 2:
        return [text]
    return [p for p in pieces if p]


def add_item(raw_text):
    text = raw_text.strip()
    if not text:
        return
    # Тело коммита бывает и служебным («Подробности ниже:»), и слишком
    # длинным для заметки: такие строки в релиз не отдаём.
    if len(text) < 6 or text.endswith(":"):
        return
    cap = 200 if SECTIONS else 140
    if len(text) > cap:
        cut = text[:cap]
        text = cut.rsplit(" ", 1)[0].rstrip(",;:—-") + "…"
    elif text.endswith((",", ";")):
        # Перенесённый пункт тела приходит без второй половины: висящая
        # запятая выдаёт обрубок, лучше честное многоточие.
        text = text[:-1].rstrip() + "…"
    text = text[0].upper() + text[1:]
    low = text.lower()
    section = section_of(low)
    # Значок сначала по теме, а если темы не узнали — по разделу, чтобы пункт
    # внутри «Плавнее» не начинался со звёздочки из «Нового».
    emoji = {"new": "✨", "polish": "🫧", "fix": "🛠️"}[section]
    for keys, icon in EMOJI_RULES:
        if any(k in low for k in keys):
            emoji = icon
            break
    bullet = "- " + emoji + " " + text
    if bullet in seen:
        return
    seen.add(bullet)
    order.append((emoji, text))
    human = humanize(text)
    # После вырезания имён от пункта иногда остаётся два слова («Тест»,
    # «Экран:»): такое в заметке читается хуже, чем отсутствие строки.
    if len(human.split()) < 3:
        return
    item = {"emoji": emoji, "text": human, "detail": ""}
    buckets[section].append(item)
    global last_item
    last_item = item

for raw in sys.stdin:
    line = raw.rstrip("\n")
    # Строка с отступом — подробности предыдущего пункта: то, что автор
    # коммита написал в теле («было так, стало так»). Приклеиваем к пункту,
    # а не печатаем отдельной строкой и не выбрасываем.
    if SECTIONS and line[:1] in (" ", "\t") and line.strip():
        if last_item is not None:
            last_item["detail"] = (last_item["detail"] + " " + line.strip()).strip()
        continue
    # Перенос строки длинного пункта из changelog — не заголовок коммита,
    # отдаём как есть, иначе хвост пункта теряется. В режиме разделов тело
    # коммита приходит сырым: его прозу и заголовки не печатаем, берём только
    # готовые пункты «- …».
    if not line.startswith("- "):
        if not SECTIONS:
            print(line)
        continue
    # Срезаем Conventional Commits во всех видах, включая breaking-варианты:
    # `fix(strike)!:`, `feat!:`, `feat(scope)!:`. Раньше шаблон ждал двоеточие
    # сразу после скобки, а `!` его сдвигал — префикс не снимался, и в «Что
    # нового» попадала техническая строка «Fix(strike)! — …».
    text = re.sub(r"^(fix|feat|perf|improve|polish)(\([^)]*\))?!?:\s*", "",
                  line[2:], flags=re.I).strip()
    # Свой эмодзи-маркер ставим сами: если пункт пришёл с готовым значком
    # (старый changelog, повторный прогон), второй значок в начале читался
    # бы как «🫧 🫧 текст».
    text = re.sub(r"^[\U0001F000-\U0001FAFF\u2190-\u2BFF\uFE0F\u200D]+\s*",
                  "", text).strip()
    if not text:
        continue
    # Перечисление через «;» даёт отдельные пункты: иначе одна строка на
    # всю сборку и половина работы теряется при обрезке.
    for piece in parts_of(text):
        add_item(piece)

if not SECTIONS:
    # Порядок — как в истории: fastlane-заметки читают сверху вниз, и
    # перестановка сломала бы привычный ход «сначала главное».
    for emoji, text in order:
        print("- " + emoji + " " + text)
    raise SystemExit(0)

# Длинный список из десяти строк в релизе не читают. Держим по шесть пунктов
# на раздел: этого хватает, чтобы показать работу, и не превращает заметку в
# простыню.
LIMIT_PER_SECTION = 6
for key in ("new", "polish", "fix"):
    buckets[key] = buckets[key][:LIMIT_PER_SECTION]

total = sum(len(v) for v in buckets.values())
if total == 0:
    raise SystemExit(0)

# Вступление подбираем по составу выпуска: заметка про три починки не должна
# начинаться словами «в этой версии появилось новое» — читатель сразу видит,
# что текст писали не глядя в список изменений.
kinds = {k for k in ("new", "polish", "fix") if buckets[k]}
if kinds == {"new"}:
    lead = ("В этой сборке — новое: ниже по делу, что появилось и как этим "
            "пользоваться.")
elif kinds == {"fix"}:
    lead = ("Сборка целиком про починку: ниже — что мешало в прошлой версии "
            "и как теперь.")
elif kinds == {"polish"}:
    lead = ("Здесь ничего нового — только шлифовка: движение ровнее, отклик "
            "мягче, мелочи аккуратнее.")
else:
    lead = ("Здесь и новое, и починка старого, и шлифовка: ниже коротко, "
            "что именно поменялось.")

print("Свежая сборка Agysha — ставится поверх, вход и настройки на месте.")
print(lead)
print("")

TITLES = {
    "new": ("✨ Новое", "Что появилось в этой сборке."),
    "polish": ("🫧 Плавнее и приятнее", "Что стало ровнее и приятнее на ощупь."),
    "fix": ("🛠️ Починили", "Что мешало и теперь работает как надо."),
}
for key in ("new", "polish", "fix"):
    items = buckets[key]
    if not items:
        continue
    title, section_lead = TITLES[key]
    print("**" + title + "**")
    print(section_lead)
    for item in items:
        print("- " + item["emoji"] + " " + item["text"])
        detail = clip_detail(item["detail"])
        # Пункт без подробностей остаётся одной строкой — так бывает, когда
        # у коммита нет тела. Честно короткая заметка лучше раздутой водой
        # ради объёма.
        if detail:
            print("  " + detail)
    print("")

print("Обновляйся поверх — данные и настройки остаются. "
      "Если что-то на телефоне всё ещё дёргается или отвечает не так, "
      "напиши — починим в следующей сборке. Спасибо, что ты с нами 💛")
